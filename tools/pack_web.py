"""Pack web_ui/ into a C header the firmware can serve from flash.

The board hosts the web app itself, so "connect to it" means opening
http://192.168.4.1 with nothing installed on the PC. This script turns the
files into PROGMEM byte arrays plus a lookup table.

    python tools\\pack_web.py esp32_gadget/web_ui esp32_gadget/web_assets.h
"""

import os
import sys

MIME = {
    ".html": "text/html",
    ".css": "text/css",
    ".js": "application/javascript",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
}


def collect(root):
    files = []
    for dirpath, _dirnames, filenames in os.walk(root):
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, root).replace("\\", "/")
            files.append((rel, full))
    files.sort()
    return files


def symbol(rel):
    return "asset_" + "".join(c if c.isalnum() else "_" for c in rel)


def emit_bytes(out, rel, data):
    name = symbol(rel)
    out.append("static const uint8_t %s[] = {" % name)
    for i in range(0, len(data), 20):
        chunk = ", ".join("0x%02x" % b for b in data[i:i + 20])
        out.append("  " + chunk + ",")
    out.append("};")
    return name


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2

    root, header_path = argv[1], argv[2]
    files = collect(root)
    if not files:
        print("no files under %s" % root)
        return 1

    out = [
        "// Generated by tools/pack_web.py from %s - do not edit by hand."
        % os.path.basename(root.rstrip("/\\")),
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "struct WebAsset {",
        "  const char *path;",
        "  const char *mime;",
        "  const uint8_t *data;",
        "  uint32_t len;",
        "};",
        "",
    ]

    names = []
    total = 0
    for rel, full in files:
        with open(full, "rb") as handle:
            data = handle.read()
        total += len(data)
        names.append((rel, emit_bytes(out, rel, data)))
        out.append("")

    out.append("static const WebAsset WEB_ASSETS[] = {")
    for rel, name in names:
        ext = os.path.splitext(rel)[1].lower()
        mime = MIME.get(ext, "application/octet-stream")
        out.append('  {"/%s", "%s", %s, sizeof(%s)},' % (rel, mime, name, name))
    out.append("};")
    out.append("static const uint32_t WEB_ASSET_COUNT = %d;" % len(names))
    out.append("")

    os.makedirs(os.path.dirname(header_path) or ".", exist_ok=True)
    with open(header_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))

    print("packed %d files, %d bytes -> %s" % (len(names), total, header_path))
    for rel, _name in names:
        print("   /%s" % rel)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
