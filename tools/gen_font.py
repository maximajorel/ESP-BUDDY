# Every glyph the renderer can meet must exist, so unknown characters are drawn
# as a filled block instead of silently disappearing.
FALLBACK = ["#####", "#####", "#####", "#####", "#####", "#####", "#####"]


# Labels are comments only, but a backslash there would splice the next
# line into the comment and drop a glyph from the table.
LABELS = {" ": "space", "\\": "backslash"}

def pack(rows):
    """Rows of '#'/'.' -> 5 column bytes, bit 0 = top row."""
    cols = []
    for c in range(5):
        value = 0
        for r in range(7):
            if rows[r][c] == "#":
                value |= 1 << r
        cols.append(value)
    return cols


def validate():
    for ch, rows in GLYPHS.items():
        if len(rows) != 7:
            raise SystemExit("glyph %r has %d rows, expected 7" % (ch, len(rows)))
        for i, row in enumerate(rows):
            if len(row) != 5:
                raise SystemExit("glyph %r row %d is %d wide, expected 5"
                                 % (ch, i, len(row)))
            if set(row) - set("#."):
                raise SystemExit("glyph %r row %d has stray characters" % (ch, i))

    # The firmware indexes the table as FONT_GLYPHS[code - FONT_FIRST], so a
    # missing code point in the middle would silently shift every later glyph.
    codes = sorted(ord(ch) for ch in GLYPHS)
    expected = list(range(codes[0], codes[-1] + 1))
    if codes != expected:
        missing = sorted(set(expected) - set(codes))
        raise SystemExit("font table is not contiguous; missing code points: %s"
                         % ", ".join("%d (%r)" % (c, chr(c)) for c in missing))


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    validate()

    chars = sorted(GLYPHS, key=ord)
    out = []
    out.append("// Generated by tools/gen_font.py - do not edit by hand.")
    out.append("// 5x7 pixel font, column-major: one byte per column, bit 0 = top")
    out.append("// row. FONT_FIRST is the lowest code point in the table.")
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("#define FONT_W 5")
    out.append("#define FONT_H 7")
    out.append("#define FONT_FIRST %d" % ord(chars[0]))
    out.append("#define FONT_LAST %d" % ord(chars[-1]))
    out.append("")
    out.append("static const uint8_t FONT_GLYPHS[%d][FONT_W] = {" % len(chars))
    for ch in chars:
        data = pack(GLYPHS[ch])
        # A backslash as the label would end the line and splice the next one into
        # the comment, silently swallowing the following glyph and shifting every
        # code after it. That is not a theory: `// \` cost the ']' row, which
        # moved every lowercase letter one glyph forward on the panel.
        label = LABELS.get(ch, ch)
        line = "  { %s },  // %s" % (", ".join("0x%02x" % b for b in data), label)
        if line.rstrip().endswith("\\"):
            raise SystemExit("generated line ends with a backslash: %r" % line)
        out.append(line)
    out.append("};")
    out.append("")
    out.append("// Drawn when a code point falls outside the table.")
    out.append("static const uint8_t FONT_FALLBACK[FONT_W] = { %s };"
               % ", ".join("0x%02x" % b for b in pack(FALLBACK)))
    out.append("")

    text = "\n".join(out)
    with open(argv[1], "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s: %d glyphs" % (argv[1], len(chars)))


if __name__ == "__main__":
    main(sys.argv)
